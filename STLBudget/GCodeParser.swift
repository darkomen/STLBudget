import Foundation

// Parses OrcaSlicer metadata without executing the G-code.
enum GCodeParser {
    static func parse(_ url: URL) throws -> PrintJob {
        let data = try Data(contentsOf: url, options: .mappedIfSafe)
        guard let content = String(data: data, encoding: .utf8) else {
            throw NSError(domain: "STLBudget", code: 1, userInfo: [NSLocalizedDescriptionKey: "El G-code no es texto UTF-8 válido."])
        }
        var job = PrintJob(name: url.deletingPathExtension().lastPathComponent)
        let lines = content.components(separatedBy: .newlines)
        var thumbnails: [(size: Int, data: Data)] = []
        // OrcaSlicer: cada objeto aparece varias veces (una por capa).
        // La identidad de copia evita contar capas como piezas distintas.
        var detectedObjects: [String: Set<String>] = [:]
        let objectRegex = try? NSRegularExpression(pattern: #"^;\s*printing object (.+?) id:([^ ]+) copy (\d+)"#)
        var readingThumbnail = false
        var thumbText = ""
        var thumbSize = 0
        for raw in lines {
            let line = raw.trimmingCharacters(in: .whitespacesAndNewlines)
            if readingThumbnail {
                if line.hasPrefix("; thumbnail end") {
                    if let bytes = Data(base64Encoded: thumbText, options: .ignoreUnknownCharacters) {
                        thumbnails.append((thumbSize, bytes))
                    }
                    readingThumbnail = false
                    thumbText = ""
                } else { thumbText += line.hasPrefix(";") ? String(line.dropFirst()).trimmingCharacters(in: .whitespaces) : line }
                continue
            }
            if line.hasPrefix("; thumbnail begin") {
                let parts = line.split(separator: " ")
                if parts.count >= 4 {
                    let dims = parts[3].split(separator: "x")
                    if dims.count == 2, let w = Int(dims[0]), let h = Int(dims[1]) {
                        readingThumbnail = true; thumbSize = w * h
                    }
                }
                continue
            }
            if line.hasPrefix("; printing object "), let regex = objectRegex,
               let match = regex.firstMatch(in: line, range: NSRange(line.startIndex..., in: line)),
               let nameRange = Range(match.range(at: 1), in: line),
               let idRange = Range(match.range(at: 2), in: line),
               let copyRange = Range(match.range(at: 3), in: line) {
                let name = String(line[nameRange]); let identity = String(line[idRange]) + ":" + String(line[copyRange])
                detectedObjects[name, default: []].insert(identity)
            }
            if line.hasPrefix("; total layer number:") { job.layers = Int(line.split(separator: ":").last?.trimmingCharacters(in: .whitespaces) ?? "") }
            if line.hasPrefix("; generated by ") { job.slicer = String(line.dropFirst("; generated by ".count)) }
            if line.hasPrefix("SET_ACTIVE_SPOOL") {
                if let range = line.range(of: #"\bID\s*=\s*(\d+)"#, options: .regularExpression) {
                    job.spoolID = Int(line[range].split(separator: "=").last?.trimmingCharacters(in: .whitespaces) ?? "")
                }
            }
            guard line.hasPrefix(";") else { continue }
            let metadata = String(line.dropFirst()).trimmingCharacters(in: .whitespaces)
            let parts = metadata.split(separator: "=", maxSplits: 1).map { $0.trimmingCharacters(in: .whitespaces) }
            guard parts.count == 2 else { continue }
            let key = parts[0], value = parts[1].trimmingCharacters(in: CharacterSet(charactersIn: "\""))
            switch key {
            case "filament used [g]", "total filament used [g]": job.grams = Double(value)
            case "estimated printing time (normal mode)": job.durationSeconds = duration(value)
            case "filament_type": job.material = value
            case "filament_settings_id": job.profile = value
            case "nozzle_temperature": job.nozzleC = Double(value.components(separatedBy: ",")[0])
            case "first_layer_bed_temperature": job.bedC = Double(value.components(separatedBy: ",")[0])
            case "total layer number": job.layers = Int(value)
            default: break
            }
        }
        job.objects = detectedObjects.keys.sorted().map { GCodeObject(name: $0, copies: detectedObjects[$0]?.count ?? 1) }
        job.thumbnail = thumbnails.max(by: { $0.size < $1.size })?.data
        if job.grams == nil { job.notes.append("No aparece consumo en gramos: introduce el valor manualmente.") }
        if job.durationSeconds == nil { job.notes.append("No aparece estimación de tiempo.") }
        if job.spoolID == nil { job.notes.append("No se encontró SET_ACTIVE_SPOOL ID=…") }
        return job
    }

    private static func duration(_ text: String) -> Int? {
        let pattern = #"(?:(\d+)d\s*)?(?:(\d+)h\s*)?(?:(\d+)m\s*)?(?:(\d+)s)?"#
        guard let regex = try? NSRegularExpression(pattern: pattern),
              let match = regex.firstMatch(in: text, range: NSRange(text.startIndex..., in: text)),
              match.range.length > 0 else { return nil }
        let factors = [86400, 3600, 60, 1]
        return (1...4).reduce(0) { sum, idx in
            guard let range = Range(match.range(at: idx), in: text), let n = Int(text[range]) else { return sum }
            return sum + n * factors[idx - 1]
        }
    }
}
